const months: Record<string,string> = {
  Jan:"ஜன.", Feb:"பிப்.", Mar:"மார்.", Apr:"ஏப்.", May:"மே", Jun:"ஜூன்",
  Jul:"ஜூலை", Aug:"ஆக.", Sep:"செப்.", Oct:"அக்.", Nov:"நவ.", Dec:"டிச.",
};

function preserveOuterWhitespace(source:string, translated:string){
  const lead=source.match(/^\s*/)?.[0]??"";
  const trail=source.match(/\s*$/)?.[0]??"";
  return `${lead}${translated}${trail}`;
}

function translateDateFragments(value:string){
  let out=value;
  for(const [en,ta] of Object.entries(months)) out=out.replace(new RegExp(`\\b${en}\\b`,"g"),ta);
  return out.replace(/\bAM\b/g,"மு.ப").replace(/\bPM\b/g,"பி.ப");
}

export function translateAtlasText(source:string, language:AtlasLanguage){
  if(language==="en" || !source) return source;
  const core=source.trim();
  if(!core) return source;
  const direct=TA[core];
  if(direct) return preserveOuterWhitespace(source,direct);

  let match=core.match(/^(\d+)m ago$/);
  if(match) return preserveOuterWhitespace(source,`${match[1]} நிமி முன்`);
  match=core.match(/^(\d+)h ago$/);
  if(match) return preserveOuterWhitespace(source,`${match[1]} மணி முன்`);
  match=core.match(/^(\d+)d ago$/);
  if(match) return preserveOuterWhitespace(source,`${match[1]} நாள் முன்`);
  if(core==="just now") return preserveOuterWhitespace(source,"இப்போதுதான்");

  match=core.match(/^of (\d+) stories$/);
  if(match) return preserveOuterWhitespace(source,`${match[1]} செய்திகளில்`);
  match=core.match(/^(\d+) active$/);
  if(match) return preserveOuterWhitespace(source,`${match[1]} செயலில்`);
  match=core.match(/^View all (\d+) headlines$/);
  if(match) return preserveOuterWhitespace(source,`அனைத்து ${match[1]} தலைப்புகளையும் பார்க்க`);
  match=core.match(/^Headline (\d+) of (\d+)$/);
  if(match) return preserveOuterWhitespace(source,`தலைப்பு ${match[1]} / ${match[2]}`);
  match=core.match(/^BEST (\d+)$/);
  if(match) return preserveOuterWhitespace(source,`சிறந்த ${match[1]}`);
  match=core.match(/^(World|Sports|Entertainment) (\d+)$/);
  if(match) return preserveOuterWhitespace(source,`${TA[match[1]]??match[1]} ${match[2]}`);
  match=core.match(/^Search: “(.+)”$/);
  if(match) return preserveOuterWhitespace(source,`தேடல்: “${match[1]}”`);
  match=core.match(/^Show (\d+) (.+) stories$/);
  if(match) return preserveOuterWhitespace(source,`${TA[match[2]]??match[2]} பிராந்தியத்தின் ${match[1]} செய்திகளை காட்டு`);
  match=core.match(/^Remove (.+) from saved stories$/);
  if(match) return preserveOuterWhitespace(source,`சேமித்த செய்திகளில் இருந்து நீக்குக: ${match[1]}`);
  match=core.match(/^Search (entertainment|sports) headlines$/);
  if(match) return preserveOuterWhitespace(source,`${TA[match[1]==="sports"?"Sports":"Entertainment"]} தலைப்புகளில் தேடுக`);
  match=core.match(/^Search (entertainment|sports), people, teams, places$/);
  if(match) return preserveOuterWhitespace(source,`${TA[match[1]==="sports"?"Sports":"Entertainment"]}, நபர்கள், அணிகள், இடங்களைத் தேடுக`);
  match=core.match(/^Updated (.+) ago$/);
  if(match) return preserveOuterWhitespace(source,`புதுப்பிப்பு ${translateAtlasText(match[1]+" ago","ta")}`);
  match=core.match(/^(\d+) signals$/);
  if(match) return preserveOuterWhitespace(source,`${match[1]} சமிக்ஞைகள்`);
  match=core.match(/^(\d+) related signals$/);
  if(match) return preserveOuterWhitespace(source,`${match[1]} தொடர்புடைய சமிக்ஞைகள்`);
  match=core.match(/^(\d+) hours$/);
  if(match) return preserveOuterWhitespace(source,`${match[1]} மணிநேரம்`);
  if(core==="7 days") return preserveOuterWhitespace(source,"7 நாட்கள்");
  match=core.match(/^Published (.+)$/);
  if(match) return preserveOuterWhitespace(source,`வெளியிடப்பட்டது ${translateDateFragments(match[1])}`);
  match=core.match(/^Feeds checked (.+)$/);
  if(match) return preserveOuterWhitespace(source,`ஊட்டங்கள் சரிபார்க்கப்பட்ட நேரம் ${translateDateFragments(match[1])}`);
  match=core.match(/^Open the original (.+) article$/);
  if(match) return preserveOuterWhitespace(source,`${match[1]} மூலக் கட்டுரையைத் திறக்க`);

  // Date-only interface nodes/titles can safely localize month/meridiem fragments.
  if(/\b(?:Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec)\b|\b(?:AM|PM)\b/.test(core)){
    return preserveOuterWhitespace(source,translateDateFragments(core));
  }
  return source;
}
